// Ex 1 — Use while para imprimir os numeros de 1 a 10.

package repeticao;

public class Ex1 {
    public static void main(String[] args) {

        int numero = 1;

        while (numero <= 10) {
            System.out.println("Você está lendo o número " + numero);
            numero++;
        }
        
    }
}
